'use strict';

const OPERATIONS = Object.freeze(['claim', 'release', 'handoff']);
const COMMAND = '/issue-claim ';
const KNOWN_SIGNATURES = Object.freeze(['\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_']);
const ID = /^[a-zA-Z0-9][a-zA-Z0-9._-]{2,79}$/;
const MARKER = /^<!-- issue-claim:v2 (.+) -->\n/;
const BOT = 'github-actions[bot]';

function parseCommentRequest(body) {
  if (typeof body !== 'string' || !body.startsWith(COMMAND) || body.length > 2000) {
    throw Error('Use /issue-claim followed by one JSON object (max 2000 characters)');
  }
  let text = body.slice(COMMAND.length).replace(/\r\n/g, '\n').trimEnd();
  const signature = KNOWN_SIGNATURES.find(value => text.endsWith(value));
  if (signature) text = text.slice(0, -signature.length);
  let request;
  try { request = JSON.parse(text); } catch { throw Error('Invalid request JSON'); }
  const allowed = ['operation', 'issue', 'owner', 'agent', 'request_id', 'summary'];
  if (!request || Array.isArray(request) || typeof request !== 'object' ||
      Object.keys(request).some(key => !allowed.includes(key)) ||
      Object.entries(request).some(([key, value]) => key === 'issue' ? !['string', 'number'].includes(typeof value) : typeof value !== 'string')) {
    throw Error('Invalid request fields');
  }
  return request;
}

async function commentsFor(github, context, number) {
  return github.paginate(github.rest.issues.listComments, {...context.repo, issue_number:number, per_page:100});
}

function ledger(comments) {
  // v1 reservations, including all old waiting/recovery records, are invalid.
  // Keep the historical comments intact; only the new protocol creates v2 records.
  return comments.filter(comment => comment.user?.login === BOT && MARKER.test(comment.body || ''))
    .map(comment => ({comment, record:JSON.parse(comment.body.match(MARKER)[1])}))
    .sort((a, b) => a.comment.id - b.comment.id);
}

async function requireWriter(github, context, username) {
  const {data} = await github.rest.repos.getCollaboratorPermissionLevel({...context.repo, username});
  if (!['write', 'maintain', 'admin'].includes(data.permission)) throw Error('Repository write permission required');
}

async function recheckComment(github, context) {
  const prior = context.requestComment;
  if (!prior) return;
  const {data:current} = await github.rest.issues.getComment({...context.repo, comment_id:prior.id});
  if (current.body !== prior.body || current.user?.login !== prior.user.login ||
      current.issue_url !== prior.issue_url || current.updated_at !== prior.updated_at) {
    throw Error('Request comment changed');
  }
  await requireWriter(github, context, prior.user.login);
}

async function coordinate(github, context, core, inputs = process.env) {
  const op = inputs.OPERATION;
  const owner = inputs.OWNER || '';
  const issue = String(inputs.ISSUE || '');
  const summary = inputs.SUMMARY || '';
  const request = inputs.REQUEST_ID || '';
  const agent = inputs.AGENT || 'any';
  if (!OPERATIONS.includes(op)) throw Error('Use claim, release or handoff');
  if (!/^[1-9][0-9]*$/.test(issue) || !Number.isSafeInteger(Number(issue))) throw Error('Invalid Issue number');
  if (typeof owner !== 'string' || !ID.test(owner)) throw Error('Invalid owner ID');
  if (typeof request !== 'string' || (request && !ID.test(request))) throw Error('Invalid request ID');
  if (!['any', 'codex', 'claude'].includes(agent)) throw Error('Invalid agent');
  if (op === 'handoff' ? (typeof summary !== 'string' || !summary.trim() || summary.length > 1200 || summary.includes('<!--')) : summary !== '') {
    throw Error('Only handoff accepts a required summary of 1–1200 characters without HTML comments');
  }
  if (Number(context.runAttempt || 1) !== 1) throw Error('Submit a new request instead of rerunning a reservation job');
  await requireWriter(github, context, context.actor);
  const number = Number(issue);
  const {data:target} = await github.rest.issues.get({...context.repo, issue_number:number});
  if (target.pull_request) throw Error('Target must be an Issue, not a PR');
  if (op === 'claim' && (target.state !== 'open' || target.labels.some(label =>
      ['blocked', 'status:blocked'].includes(typeof label === 'string' ? label : label.name)))) {
    throw Error('Claim requires an open, unblocked Issue');
  }
  const entries = ledger(await commentsFor(github, context, number));
  if (entries.some(({record}) => String(record.run) === String(context.runId) || (request && record.request === request))) {
    throw Error('Request already recorded; inspect the Issue ledger');
  }
  const latest = entries.at(-1)?.record;
  if (op === 'claim') {
    if (latest?.state === 'claimed') throw Error('Already claimed by ' + latest.owner);
  } else if (latest?.state !== 'claimed' || latest.owner !== owner || latest.actor !== context.actor) {
    throw Error('Only the current owner and requester may release or handoff');
  }
  await recheckComment(github, context);
  const state = op === 'claim' ? 'claimed' : op === 'release' ? 'released' : 'handoff';
  const record = {state, owner, actor:context.actor, run:String(context.runId), request};
  const detail = op === 'claim' ? 'Reserved by ' + owner + ' (' + agent + ').' :
    op === 'release' ? 'Released by ' + owner + '.' : 'Handed off by ' + owner + '; available for claim.\n\n' +
      summary.split('\n').map(line => '> ' + line).join('\n');
  await github.rest.issues.createComment({...context.repo, issue_number:number,
    body:'<!-- issue-claim:v2 ' + JSON.stringify(record) + ' -->\n' + detail});
  const result = (op === 'claim' ? 'CLAIMED' : op === 'release' ? 'RELEASED' : 'HANDED_OFF') + '_ISSUE=' + number + ' OWNER=' + owner;
  core.notice(result);
  await core.summary.addRaw(result).write();
}

async function runEvent(github, context, core, inputs = process.env) {
  const branch = context.payload.repository.default_branch;
  if (context.eventName === 'workflow_dispatch') {
    if (context.ref !== 'refs/heads/' + branch) throw Error('Run reservation requests on the default branch');
    return coordinate(github, context, core, inputs);
  }
  if (context.eventName !== 'issue_comment') throw Error('Unsupported event');
  const comment = context.payload.comment;
  if (context.payload.action !== 'created' || comment?.user?.type === 'Bot' || !comment?.body?.startsWith(COMMAND)) return;
  await requireWriter(github, context, comment.user.login);
  const {data:current} = await github.rest.issues.getComment({...context.repo, comment_id:comment.id});
  if (current.body !== comment.body || current.user?.login !== comment.user.login ||
      current.issue_url !== context.payload.issue.url) throw Error('Request comment changed or belongs to a different Issue');
  const receipt = '<!-- issue-claim-request:v2 comment=' + comment.id + ' -->';
  if ((await commentsFor(github, context, context.payload.issue.number)).some(entry =>
      entry.user?.login === BOT && entry.body?.startsWith(receipt))) return;
  let failure;
  try {
    const request = parseCommentRequest(current.body);
    // The queue is keyed by the thread Issue. Cross-Issue requests would race
    // with that Issue's own queue and are deliberately not accepted.
    if (request.issue !== undefined && String(request.issue) !== String(context.payload.issue.number)) {
      throw Error('Post the request on its target Issue');
    }
    const requestContext = Object.assign(Object.create(context), {actor:current.user.login, requestComment:current});
    await coordinate(github, requestContext, core, {
      OPERATION:request.operation, ISSUE:String(context.payload.issue.number), OWNER:request.owner,
      AGENT:request.agent, REQUEST_ID:request.request_id || 'comment-' + current.id, SUMMARY:request.summary});
  } catch (error) { failure = error; }
  await github.rest.issues.createComment({...context.repo, issue_number:context.payload.issue.number,
    body:receipt + '\n' + (failure ? 'Request refused: ' + failure.message : 'Request recorded; wait for this run to succeed.') +
      '\nRun: ' + (context.serverUrl || 'https://github.com') + '/' + context.repo.owner + '/' + context.repo.repo + '/actions/runs/' + context.runId});
  if (failure) throw failure;
}

module.exports = {coordinate, runEvent, parseCommentRequest, OPERATIONS, KNOWN_SIGNATURES};
