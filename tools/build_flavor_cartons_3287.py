#!/usr/bin/env python3
"""Build the adopted Issue #3287 cartons (and the #3221 coffee carton) for the shop without editing originals."""
import argparse
import hashlib
import io
import json
from pathlib import Path

from PIL import Image
from build_shop_art import inspect

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "asset_sources/flavor-cartons-20261111"
DEST = ROOT / "remake/img/shop/flavor-cartons-3287"
IDS = (
    "blueberry_mint", "cappuccino", "caramel", "chocolate", "cool_mint",
    "frozen_citrus", "jasmine", "kiwi", "sakura", "coffee",
)
# 原画が別の置き場にあるもの（#3221 C: ドバジ・コーヒー。PR #3329 で Codex が作った原画をそのまま使う）
SOURCE_OVERRIDES = {"coffee": "asset_sources/card_game/coffee-20261111/coffee.png"}
MODULE = ROOT / "remake/js/daily/shop-art-flavor-cartons-3287.js"
REPORT = SOURCE / "integration.json"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build(check):
    entries = []
    mappings = []
    for flavor_id in IDS:
        source_rel = SOURCE_OVERRIDES.get(flavor_id, f"asset_sources/flavor-cartons-20261111/{flavor_id}.png")
        native = ROOT / source_rel
        source_bytes = native.read_bytes()
        before = inspect(native)
        if before["size"] != [1254, 1254]:
            raise ValueError(f"Unexpected original dimensions: {native}")
        with Image.open(io.BytesIO(source_bytes)) as image:
            image.load()
            output = io.BytesIO()
            image.resize((512, 512), Image.Resampling.LANCZOS).save(
                output, format="WEBP", quality=88, method=6, exact=True
            )
        encoded = output.getvalue()
        delivery = DEST / f"{flavor_id}.webp"
        if check:
            if delivery.read_bytes() != encoded:
                raise ValueError(f"Delivery differs from source: {delivery}")
        else:
            delivery.parent.mkdir(parents=True, exist_ok=True)
            delivery.write_bytes(encoded)
        after = inspect(delivery)
        if native.read_bytes() != source_bytes:
            raise ValueError(f"Original changed during conversion: {native}")
        entries.append({
            "id": flavor_id,
            "source": source_rel,
            "source_sha256": sha(source_bytes),
            "delivery": f"remake/img/shop/flavor-cartons-3287/{flavor_id}.webp",
            "delivery_sha256": sha(encoded),
            "source_size": before["size"],
            "delivery_size": after["size"],
            "box": after["box"],
        })
        mappings.append(
            f'  "{flavor_id}": {{ url: new URL("../../img/shop/flavor-cartons-3287/{flavor_id}.webp", import.meta.url).href, size: [512, 512], box: {json.dumps(after["box"])} }},'
        )
    module = (
        "// Adopted Issue #3287 cartons; generated by tools/build_flavor_cartons_3287.py.\n"
        "export const FLAVOR_CARTONS_3287_ART = {\n"
        + "\n".join(mappings) + "\n};\n"
    )
    report = json.dumps({"items": entries}, indent=2, ensure_ascii=False) + "\n"
    for path, content in ((MODULE, module), (REPORT, report)):
        if check:
            if path.read_text() != content:
                raise ValueError(f"Generated metadata differs: {path}")
        else:
            path.write_text(content)
    print(f"PASS: {len(entries)} originals and 512px WebP deliveries verified")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
