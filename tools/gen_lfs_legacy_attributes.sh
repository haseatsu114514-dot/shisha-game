#!/usr/bin/env bash
# Regenerate the "legacy" block of .gitattributes: files that must stay ordinary
# Git blobs even though their path matches a Git LFS rule above the block.
#
#   assets/, remake/img/  images that already existed on origin/main stay
#                         ordinary Git (only NEW images there are LFS).
#   asset_sources/        converted to LFS on 2026-11-11 (owner decision, no
#                         history rewrite). Only the folders CI reads stay
#                         ordinary Git: every "/asset_sources/..." entry in the
#                         "sparse" lists of tools/ci/suites.json, plus
#                         asset_sources/shisha-hardware-reference/ (reference
#                         sheets read directly by people and AI).
#
# Files that are already LFS pointers on the ref are never pinned, so running
# this again after the conversion does not bring converted files back.
# Usage: git fetch origin main && tools/gen_lfs_legacy_attributes.sh [ref]
set -euo pipefail
ref="${1:-origin/main}"
root="$(git rev-parse --show-toplevel)"
file="$root/.gitattributes"
begin='# BEGIN legacy non-LFS images (generated by tools/gen_lfs_legacy_attributes.sh)'
end='# END legacy non-LFS images'
tmp="$(mktemp)"
keep="$(mktemp)"
trap 'rm -f "$tmp" "$keep"' EXIT

# asset_sources paths that stay ordinary Git (folders end with "/").
{
  printf '%s\n' 'asset_sources/shisha-hardware-reference/'
  git show "$ref:tools/ci/suites.json" | python3 -c '
import json, sys
for suite in json.load(sys.stdin)["suites"]:
    for path in suite.get("sparse", []):
        path = path.lstrip("/")
        if path.startswith("asset_sources/"):
            print(path)'
} | sort -u > "$keep"

# Keep everything outside the generated block.
awk -v b="$begin" -v e="$end" '$0==b{skip=1;next} $0==e{skip=0;next} !skip' "$file" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' > "$tmp"
{
  cat "$tmp"
  printf '\n%s\n' "$begin"
  # Only blobs that are real files (not already LFS pointers) are pinned.
  git ls-tree -r -l "$ref" -- assets remake/img asset_sources \
    | awk -v keepfile="$keep" '
        BEGIN { while ((getline k < keepfile) > 0) keep[++n] = k }
        {
          path = $5; lower = tolower(path)
          if (index(path, "asset_sources/") == 1) {
            if (lower !~ /\.(png|jpe?g|webp|gif|mp4|webm|mov|zip|pdf)$/) next
            kept = 0
            for (i = 1; i <= n; i++) {
              k = keep[i]
              if (path == k || (substr(k, length(k)) == "/" && index(path, k) == 1)) { kept = 1; break }
            }
            if (!kept) next
          } else if (lower !~ /\.(png|jpe?g|webp|gif)$/) next
          print $3, $4, path
        }' \
    | while read -r oid size path; do
        # LFS pointer files are tiny text blobs starting with the LFS spec line.
        if [ "$size" -lt 1024 ] && git cat-file -p "$oid" | head -c 40 | grep -q '^version https://git-lfs'; then
          continue
        fi
        printf '%s\n' "$path"
      done \
    | sed -e 's/[][*?!#\\ ]/\\&/g' \
    | LC_ALL=C sort \
    | sed -e 's/$/ !filter !diff !merge text=auto eol=lf/'
  printf '%s\n' "$end"
} > "$file"
echo "pinned $(awk -v b="$begin" -v e="$end" '$0==b{c=1;next} $0==e{c=0} c' "$file" | wc -l) legacy files in .gitattributes"
