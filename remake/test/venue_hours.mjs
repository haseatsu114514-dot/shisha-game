import assert from "node:assert/strict";
import { openingStatus, rinUnavailable } from "../js/daily/spot-hours.js";
import { newDayTrial, rollDayTrial, stopDayTrial } from "../js/trpg/day-trial.js";
import { AXE_BAR } from "../js/daily/axe-bar-data.js";

const day = { day: 5, slot: 0, visitedDay: {} }, night = { ...day, slot: 1 };
assert(!openingStatus(AXE_BAR, day).ok);
assert(openingStatus(AXE_BAR, night).ok);
assert(!openingStatus(AXE_BAR, { ...night, slot: 2 }).ok);
assert(openingStatus({ openSlots: [0] }, day).ok);
assert(!openingStatus({ openSlots: [0] }, night).ok);
assert(openingStatus({ kind: "shop" }, day).ok);
assert(openingStatus({ kind: "shop" }, night).ok);
assert.match(rinUnavailable(day), /夜/);
assert.equal(rinUnavailable(night), "");
assert.match(rinUnavailable({ ...night, day: 2 }), /出張/);
assert.match(rinUnavailable({ ...night, visitedDay: { rin: 5 } }), /訪問済み/);
const trial = newDayTrial();
assert.strictEqual(stopDayTrial(trial), trial, "Before rolling, there is no score to lock in");
assert.strictEqual(rollDayTrial(trial, 0), trial);
assert.strictEqual(rollDayTrial(trial, 7), trial);
assert.strictEqual(rollDayTrial(trial, NaN), trial);
const six = rollDayTrial(trial, 6);
assert.deepEqual(trial, newDayTrial(), "The input snapshot is not mutated");
assert.deepEqual(stopDayTrial(six), { total: 6, rolls: [6], done: true });
const seven = rollDayTrial(six, 1);
assert.deepEqual(seven, { total: 7, rolls: [6, 1], done: true });
assert.strictEqual(rollDayTrial(seven, 6), seven, "A finished trial cannot be rolled again");
assert.deepEqual(rollDayTrial(six, 6), { total: 12, rolls: [6, 6], done: true });
console.log("Venue hours and day trial: 20 assertions PASS");
