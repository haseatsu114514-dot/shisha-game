#!/usr/bin/env node
// 起動時に 300 本超の ES モジュールを波状取得しないよう、本編の静的グラフを 1 本にまとめる（#3552）。
// 動的 import も含めて 1 本にまとめる（初回の往復を減らす）。正本は remake/js/ の各ファイル。
//
//   node remake/tools/build_js_bundle.mjs           # 生成（公開の deploy-pages.yml が毎回実行する）
//   node remake/tools/build_js_bundle.mjs --check   # 一時フォルダに作れるかだけ確かめる（CI）
//
// 生成物 js/bundle/ はコミットしない（.gitignore）。コミットすると remake/js を触る PR が
// 全部バンドルの再生成と競合を抱えるため、公開時にだけ作る。
//
// import.meta.url の相対（../../img、../../../assets）は、出力先を js/bundle/ に置くことで
// 元ファイル（js/<dir>/file.js）と同じ深さになり、差し替えない。
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const TOOLS = fileURLToPath(new URL(".", import.meta.url));
const REMAKE = path.resolve(TOOLS, "..");
const ENTRY = path.join(REMAKE, "js/main.js");
const OUTDIR = path.join(REMAKE, "js/bundle");
const CHECK = process.argv.includes("--check");

function resolveEsbuild() {
  const require = createRequire(import.meta.url);
  const dirs = [
    path.join(TOOLS, "node_modules"),
    process.env.ESBUILD_NODE_MODULES,
    path.join(REMAKE, "node_modules"),
    "/tmp/esbuild-pkg/node_modules",
  ].filter(Boolean);
  for (const dir of dirs) {
    const file = path.join(dir, "esbuild/lib/main.js");
    if (fs.existsSync(file)) return require(file);
  }
  try { return require("esbuild"); } catch {}
  const npx = spawnSync("npx", ["--yes", "esbuild@0.25.12", "--version"], { encoding: "utf8", stdio: "inherit" });
  if (npx.status !== 0) {
    console.error("esbuild を解決できません。npm install esbuild か ESBUILD_NODE_MODULES= を設定してください。");
    process.exit(1);
  }
  return require(path.join(process.cwd(), "node_modules/esbuild/lib/main.js"));
}

const esbuild = resolveEsbuild();

const banner = "/* GENERATED by remake/tools/build_js_bundle.mjs — 直接編集しないこと。正本は remake/js/ の各ファイル。 */\n";

const options = {
  absWorkingDir: REMAKE,
  entryPoints: [ENTRY],
  bundle: true,
  splitting: false,
  format: "esm",
  platform: "browser",
  target: "es2022",
  outfile: path.join(OUTDIR, "main.js"),
  sourcemap: false,
  legalComments: "none",
  // Only trim the generated download; keep identifiers and syntax unchanged.
  minifyWhitespace: true,
  logLevel: "warning",
  banner: { js: banner },
};

async function buildTo(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const outfile = path.join(dir, "main.js");
  const result = await esbuild.build({ ...options, outdir: undefined, outfile, metafile: true, write: true });
  const files = fs.readdirSync(dir).sort();
  return { files, result };
}

if (CHECK) {
  const tmp = fs.mkdtempSync(path.join(fs.realpathSync("/tmp"), "js-bundle-"));
  try {
    const { files, result } = await buildTo(tmp);
    const problems = [];
    if (result.errors.length) problems.push(`esbuild のエラー ${result.errors.length} 件`);
    if (result.warnings.length) problems.push(`esbuild の警告 ${result.warnings.length} 件（直してから公開する）`);
    if (files.join(",") !== "main.js") problems.push(`出力が main.js 1 本ではありません: ${files.join(", ")}`);
    const code = fs.readFileSync(path.join(tmp, "main.js"), "utf8");
    if (!/export\s*\{[^}]*\bboot\b[^}]*\}/.test(code)) problems.push("バンドルが boot を export していません（index.html の起動が失敗する）");
    if (/\bimport\s*\(\s*["'`]\.{1,2}\//.test(code)) problems.push("相対パスの動的 import が残っています（bundle/ からだと読み先がずれる）");
    if (problems.length) {
      for (const p of problems) console.error(p);
      process.exit(1);
    }
    console.log(`js bundle ok (main.js ${(code.length / 1024).toFixed(0)} KB, ${Object.keys(result.metafile.inputs).length} modules)`);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
} else {
  const { files } = await buildTo(OUTDIR);
  const main = path.join(OUTDIR, "main.js");
  const size = fs.statSync(main).size;
  console.log(`wrote js/bundle/ (${files.length} outputs, main.js ${(size / 1024).toFixed(0)} KB)`);
}
