#!/usr/bin/env node
// 起動時に 300 本超の ES モジュールを波状取得しないよう、本編の静的グラフを 1 本にまとめる（#3552）。
// 動的 import も含めて 1 本にまとめる（初回の往復を減らす）。正本は remake/js/ の各ファイル。
//
//   node remake/tools/build_js_bundle.mjs           # 再生成
//   node remake/tools/build_js_bundle.mjs --check   # 鮮度チェック（CI）
//
// import.meta.url の相対（../../img、../../../assets）は、出力先を js/bundle/ に置くことで
// 元ファイル（js/<dir>/file.js）と同じ深さになり、差し替えない。
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const TOOLS = fileURLToPath(new URL(".", import.meta.url));
const REMAKE = path.resolve(TOOLS, "..");
const ENTRY = path.join(REMAKE, "js/main.js");
const OUTDIR = path.join(REMAKE, "js/bundle");
const CHECK = process.argv.includes("--check");

function resolveEsbuild() {
  const require = createRequire(import.meta.url);
  const dirs = [
    path.join(TOOLS, "node_modules"),
    process.env.ESBUILD_NODE_MODULES,
    path.join(REMAKE, "node_modules"),
    "/tmp/esbuild-pkg/node_modules",
  ].filter(Boolean);
  for (const dir of dirs) {
    const file = path.join(dir, "esbuild/lib/main.js");
    if (fs.existsSync(file)) return require(file);
  }
  try { return require("esbuild"); } catch {}
  const npx = spawnSync("npx", ["--yes", "esbuild@0.25.12", "--version"], { encoding: "utf8", stdio: "inherit" });
  if (npx.status !== 0) {
    console.error("esbuild を解決できません。npm install esbuild か ESBUILD_NODE_MODULES= を設定してください。");
    process.exit(1);
  }
  return require(path.join(process.cwd(), "node_modules/esbuild/lib/main.js"));
}

const esbuild = resolveEsbuild();

const banner = "/* GENERATED by remake/tools/build_js_bundle.mjs — 直接編集しないこと。正本は remake/js/ の各ファイル。 */\n";

const options = {
  absWorkingDir: REMAKE,
  entryPoints: [ENTRY],
  bundle: true,
  splitting: false,
  format: "esm",
  platform: "browser",
  target: "es2022",
  outfile: path.join(OUTDIR, "main.js"),
  sourcemap: false,
  legalComments: "none",
  minify: false,
  logLevel: "warning",
  banner: { js: banner },
};

async function buildTo(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const outfile = path.join(dir, "main.js");
  const result = await esbuild.build({ ...options, outdir: undefined, outfile, metafile: true, write: true });
  const files = fs.readdirSync(dir).sort();
  return { files, result };
}

function sha256(buf) {
  return createHash("sha256").update(buf).digest("hex");
}

function describeMismatch(name, rebuilt, committed) {
  if (rebuilt.length !== committed.length) {
    return `${name} 長さが違います: 再生成 ${rebuilt.length} / コミット ${committed.length}`;
  }
  let i = 0;
  while (i < rebuilt.length && rebuilt[i] === committed[i]) i++;
  return `${name} 先頭の差 @${i} sha256 再生成=${sha256(rebuilt).slice(0, 16)} コミット=${sha256(committed).slice(0, 16)}`;
}

function compareBundle(dir) {
  const expected = fs.readdirSync(dir).sort();
  const actual = fs.existsSync(OUTDIR) ? fs.readdirSync(OUTDIR).sort() : [];
  const problems = [];
  if (expected.length !== actual.length || expected.some((n, i) => n !== actual[i])) {
    problems.push(`js/bundle の構成が古いです。再生成してください: ${actual.join(", ")} != ${expected.join(", ")}`);
  } else {
    for (const name of expected) {
      const a = fs.readFileSync(path.join(dir, name));
      const b = fs.readFileSync(path.join(OUTDIR, name));
      if (Buffer.compare(a, b) !== 0) problems.push(`バンドルが古いです。再生成してください: js/bundle/${name}（${describeMismatch(name, a, b)}）`);
    }
  }
  return problems;
}

if (CHECK) {
  const tmp = fs.mkdtempSync(path.join(fs.realpathSync("/tmp"), "js-bundle-"));
  try {
    await buildTo(tmp);
    let problems = compareBundle(tmp);
    if (problems.length) {
      // 稀な非決定性に備えて一度だけ作り直して比べる
      fs.rmSync(tmp, { recursive: true, force: true });
      fs.mkdirSync(tmp, { recursive: true });
      await buildTo(tmp);
      problems = compareBundle(tmp);
    }
    if (problems.length) {
      for (const p of problems) console.error(p);
      process.exit(1);
    }
    console.log(`js bundle ok (${fs.readdirSync(tmp).length} files)`);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
} else {
  const { files } = await buildTo(OUTDIR);
  const main = path.join(OUTDIR, "main.js");
  const size = fs.statSync(main).size;
  console.log(`wrote js/bundle/ (${files.length} outputs, main.js ${(size / 1024).toFixed(0)} KB)`);
}
