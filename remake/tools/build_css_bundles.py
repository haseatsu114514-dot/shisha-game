#!/usr/bin/env python3
"""CSS バンドルの生成と鮮度チェック。

remake/index.html が読み込むスタイルシートは、リクエスト数を減らすため
ディレクトリ単位のバンドルに結合して配信する。元の css ファイルが正本で、
バンドルは remake/css/bundles.json の並び順どおりに @import を展開しながら
連結した生成物。ソースを編集したらこのツールで再生成すること。

使い方:
  python3 remake/tools/build_css_bundles.py           # バンドルを再生成
  python3 remake/tools/build_css_bundles.py --check   # 鮮度チェック（CI）
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # remake/
CSS_DIR = ROOT / "css"
MANIFEST = CSS_DIR / "bundles.json"
INDEX_HTML = ROOT / "index.html"

IMPORT_RE = re.compile(r'^\s*@import\s+url\(\s*["\']?([^"\')]+)["\']?\s*\)\s*;\s*$')


def expand(path: Path, seen: tuple = ()) -> str:
    """@import を再帰的に展開した CSS テキストを返す。"""
    if path in seen:
        raise SystemExit(f"@import が循環しています: {path}")
    text = path.read_text(encoding="utf-8")
    out_lines = []
    for line in text.splitlines():
        m = IMPORT_RE.match(line)
        if m:
            target = (path.parent / m.group(1)).resolve()
            out_lines.append(f"/* @import: {target.relative_to(CSS_DIR)} */")
            out_lines.append(expand(target, seen + (path,)))
        else:
            out_lines.append(line)
    return "\n".join(out_lines)


def build_segment(seg: dict) -> str:
    parts = [
        "/* GENERATED by remake/tools/build_css_bundles.py — 直接編集しないこと。"
        "正本は bundles.json に並ぶ各 css ファイル。 */"
    ]
    for rel in seg["files"]:
        src = CSS_DIR / rel
        parts.append(f"\n/* ===== css/{rel} ===== */")
        parts.append(expand(src))
    return "\n".join(parts) + "\n"


def expected_index_links(manifest: dict) -> list:
    return [seg["out"] for seg in manifest["segments"]]


def check_index(manifest: dict) -> list:
    html = INDEX_HTML.read_text(encoding="utf-8")
    links = re.findall(r'<link rel="stylesheet" href="css/([^"]+)"', html)
    expected = expected_index_links(manifest)
    if links != expected:
        return [f"index.html の stylesheet リンクがバンドル構成と一致しません: {links} != {expected}"]
    return []


def main() -> int:
    check = "--check" in sys.argv
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    problems = check_index(manifest)
    for seg in manifest["segments"]:
        content = build_segment(seg)
        out_path = CSS_DIR / seg["out"]
        if check:
            if not out_path.exists():
                problems.append(f"バンドルがありません: css/{seg['out']}")
            elif out_path.read_text(encoding="utf-8") != content:
                problems.append(f"バンドルが古いです。再生成してください: css/{seg['out']}")
        else:
            out_path.write_text(content, encoding="utf-8")
            print(f"wrote css/{seg['out']} ({len(content)} bytes, {len(seg['files'])} files)")
    if problems:
        for p in problems:
            print(f"ERROR: {p}", file=sys.stderr)
        return 1
    if check:
        print("css bundles: fresh")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
