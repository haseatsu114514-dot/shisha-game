export function evaluationOf(score) {
  return score >= 90 ? { mark: "◎", tone: "bright", index: 0, kind: "just", label: "とても良い" }
    : score >= 65 ? { mark: "○", tone: "warm", index: 1, kind: "good", label: "良い" }
      : { mark: "△", tone: "quiet", index: 2, kind: "bad", label: "次は整えよう" };
}

