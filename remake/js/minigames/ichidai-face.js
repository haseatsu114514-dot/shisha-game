// カードゲーム「一台勝負」の相手の、まばたきと口の動きのための顔の位置（2026-11-11 オーナー「（まばたき・口の動きは）いる」）。
// 立ち絵は表情ごとに1枚ずつ描いた絵で、目を閉じた絵・口だけ違う絵が無い。そこで、目と口の位置を立ち絵の座標（896×1200）で
// 持っておき、画面でまぶた（肌の色の小さな面と、閉じた目の線）と開いた口（濃い色の小さな面）を重ねて動かす。
// 足し方: 立ち絵の目と口のまわりを拡大して、目の中心と大きさ・口の中心と大きさを読む。eyes＝[中心x, 中心y, 幅, 高さ] を2つ
// （左・右）、mouth＝[中心x, 中心y, 幅, 高さ]（しゃべるときに開く口。もともと大きく開いている表情は null＝動かさない）。
// 色: skin＝まぶたの色（目の下の肌）、line＝閉じた目の線、lips＝口の中の色。
// 位置が無いキャラ・表情では、まばたきも口の動きも出さない（体の動きだけ）。
export const FACE_PARTS = Object.freeze({
  sumi: { skin: "#f2b47c", shade: "#d88e58", line: "#3a2218", lips: "#7a2f2b", faces: {
    normal: { eyes: [[409, 199, 25, 11], [458, 196, 25, 11]], mouth: [437, 234, 17, 7] },
    serious: { eyes: [[409, 198, 25, 10], [457, 193, 25, 11]], mouth: [433, 232, 17, 7] },
    smile: { eyes: [[411, 197, 25, 10], [458, 192, 26, 10]], mouth: [441, 231, 26, 8] },
    surprise: { eyes: [[413, 201, 26, 13], [461, 197, 28, 14]], mouth: null },
    thinking: { eyes: [[410, 199, 24, 10], [456, 194, 26, 11]], mouth: [437, 238, 16, 6] },
  } },
});
/** その相手・その表情の、目と口の位置。無ければ null */
export function faceParts(charId, face) {
  const c = FACE_PARTS[charId], f = c?.faces?.[face];
  return f ? { skin: c.skin, shade: c.shade, line: c.line, lips: c.lips, eyes: f.eyes, mouth: f.mouth } : null;
}
