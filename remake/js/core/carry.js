const exactFlagRules = new Map(FLAG_EXACT_RULES);
const familyMatchers = FLAG_FAMILY_RULES.map(([pattern, category]) => [
  new RegExp(`^${pattern.replace(/[.*+?^${}()|[\]\\]/g, (c) => (c === "*" ? ".*" : `\\${c}`))}$`),
  category,
]);

/** flag 名の性質分類。分類が無ければ null（呼び出し側の既定はリセット） */
export function classifyFlag(name) {
  if (exactFlagRules.has(name)) return exactFlagRules.get(name);
  for (const [re, category] of familyMatchers) if (re.test(name)) return category;
  return null;
}

/** flag の引き継ぎ判定。未分類は既定でリセット（設計書 §2.3） */
export function flagVerdict(name) {
  const category = classifyFlag(name);
  return category ? FLAG_CATEGORY_VERDICT[category] : "reset";
}

/**
 * 真エンド時点の state から、引き継ぐ項目だけを抜き出したスナップショットを作る。
 * 許可リスト方式: ここに書いた項目しか入らない。引き継ぎ率・上限の調整（§10 の判断）は
 * ここでは行わず、値はそのまま写す（所持金だけは保存形式の上限 MAX_MONEY で切る）。
 */
export function buildCarryPackage(s) {
  const data = {};
  data.stats = Object.fromEntries(STAT_KEYS.map((k) => [k, Number.isFinite(s?.stats?.[k]) ? s.stats[k] : 0]));
  data.statXp = clone(s?.statXp ?? {});
  if (s?.growth && typeof s.growth === "object" && !Array.isArray(s.growth)) {
    // 恋人EXPの先行保存と既存previewは同じ台帳。切替や周回で精算済みXPを再精算しない。
    const g = data.growth = clone(s.growth);
    g.fresh = { chapter: 1, counts: {} };
    g.firsts = { people: [], places: [] };
    g.discoveries = { recipes: [], golden: [] };
    g.read = [];
    g.chapterLog = {}; g.tournamentXp = {}; g.cleared = [];
    g.gifted = {};
    g.today = { xp: Math.max(0, (Number(g.xp) || 0) - (Number(g.settledXp) || 0)), learned: {}, gifts: [] };
    // 新しい周回は第1章から。章のはじめの盤（章末の淡い面）を引き継いだ盤で記録しておく
    g.chapterStart = { chapter: 1, nodes: Array.isArray(g.nodes) ? [...g.nodes] : [], level: g.level };
  }
  data.money = Math.min(MAX_MONEY, Math.max(0, Math.round(Number(s?.money) || 0)));
  data.flavors = clone(s?.flavors ?? []);
  data.flavorStock = clone(s?.flavorStock ?? {});
  data.flavorMastery = clone(s?.flavorMastery ?? {});
  data.flavorLessons = clone(s?.flavorLessons ?? []);
  data.recipes = clone(s?.recipes ?? {});
  data.goods = clone(s?.goods ?? []);
  // くじ: 第5章の限定台くじ（KJ05）の箱は持ち越さない。くじ券（kujiTickets）はパッケージに入れない
  data.kuji = clone(s?.kuji && typeof s.kuji === "object" && !Array.isArray(s.kuji) ? s.kuji : {});
  for (const grade of KUJI_LIMITED_GRADES) delete data.kuji[grade];
  data.reel = clone(s?.reel ?? {});
  data.best = clone(s?.best ?? {});
  // 装備: 贈答品とくじ限定の台（KJ05）を除いた所持だけを引き継ぐ。装備中の枠も、残った所持にあるものだけを残す
  // （空いた枠を既定装備に戻すのは周回開始側の仕事で、ここでは枠ごと落とす）。
  const gift = new Set([...GIFT_EQUIPMENT_IDS, ...KUJI_ONLY_EQUIPMENT]);
  data.owned = (Array.isArray(s?.owned) ? s.owned : []).filter((id) => !gift.has(id));
  const ownedSet = new Set(data.owned);
  data.equip = Object.fromEntries(Object.entries(s?.equip ?? {}).filter(([, id]) => ownedSet.has(id)));
  // 記念品: 由来が明示されていて人物由来でないものだけ（未分類は持ち越さない）
  data.keepsakes = (Array.isArray(s?.keepsakes) ? s.keepsakes : [])
    .filter((id) => KEEPSAKE_ORIGINS[id] && KEEPSAKE_ORIGINS[id] !== "person");
  // TRPG: 部活（加入状態）は人物イベント・章進行で決まるため持ち越さない
  const trpg = s?.trpg ?? {};
  data.trpg = {
    stock: clone(trpg.stock ?? []), owned: clone(trpg.owned ?? []),
    cleared: clone(trpg.cleared ?? {}), shifts: clone(trpg.shifts ?? []),
  };
  // flags: 恒久解放・UI既読だけを、立っている（truthy）ものに限って写す
  data.flags = Object.fromEntries(Object.entries(s?.flags ?? {})
    .filter(([name, v]) => !!v && flagVerdict(name) === "carry")
    .map(([name, v]) => [name, clone(v)]));
  return data;
}

